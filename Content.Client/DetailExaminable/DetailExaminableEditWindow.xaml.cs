using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Localization;
using Robust.Shared.Utility;

namespace Content.Client.DetailExaminable
{
    [GenerateTypedNameReferences]
    public sealed partial class DetailExaminableEditWindow : DefaultWindow
    {
        public event Action<string>? OnSave;

        public DetailExaminableEditWindow()
        {
            MinSize = SetSize = new Vector2(340, 240);
            RobustXamlLoader.Load(this);

            Title = Loc.GetString("detail-examinable-edit-window-title");
            ExistingLabel.Text = Loc.GetString("detail-examinable-write-existing-label");
            SaveButton.Text = Loc.GetString("detail-examinable-edit-window-save-button");
            SaveButton.OnPressed += OnSaveButtonPressed;
        }

        public void SetDescription(string text)
        {
            DescriptionEdit.TextRope = new Rope.Leaf(text);
        }

        public void SetWindowTitle(string title)
        {
            Title = title;
        }

        public void SetPlaceholder(string text)
        {
            DescriptionEdit.Placeholder = new Rope.Leaf(text);
        }

        /// <summary>
        ///     Shows the markings already on the body while writing a new one.
        /// </summary>
        public void SetExistingMarkings(string text)
        {
            if (string.IsNullOrWhiteSpace(text))
            {
                ExistingBox.Visible = false;
                return;
            }

            ExistingBox.Visible = true;
            ExistingMarkings.SetMessage(FormattedMessage.FromMarkupOrThrow(text));
        }

        private void OnSaveButtonPressed(BaseButton.ButtonEventArgs obj)
        {
            OnSave?.Invoke(Rope.Collapse(DescriptionEdit.TextRope).Trim());
        }
    }
}
